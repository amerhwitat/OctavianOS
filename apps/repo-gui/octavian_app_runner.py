#!/usr/bin/env python3
"""OctavianOS universal GUI runner for command-line Python applications.

Turns any CLI Python script into a real desktop window: argument form,
Run / Stop buttons, live stdout+stderr pane, exit-status bar, and a
"Open output folder" convenience action.

This is the runtime half of the Python->GUI conversion. The per-app
launchers generated by ``generate_python_gui_wrappers.py`` call this module.

Usage:
    octavian_app_runner.py --target /opt/octavianos/repos/nlp/search_engines.py
"""

from __future__ import annotations

import argparse
import os
import queue
import shlex
import signal
import subprocess
import sys
import threading
import time
from pathlib import Path

try:
    import tkinter as tk
    from tkinter import filedialog, messagebox, ttk
except Exception:  # pragma: no cover - headless
    tk = None


THEME = {
    "bg": "#0f1420",
    "panel": "#161d2e",
    "fg": "#e8eefc",
    "accent": "#4da3ff",
    "ok": "#39d98a",
    "err": "#ff6b6b",
    "mono": ("DejaVu Sans Mono", 10),
    "ui": ("DejaVu Sans", 10),
}


class AppRunner:
    def __init__(self, target: Path, title: str | None = None, cwd: Path | None = None):
        self.target = target
        self.cwd = cwd or target.parent
        self.proc: subprocess.Popen | None = None
        self.q: queue.Queue[str] = queue.Queue()
        self.started = 0.0

        self.root = tk.Tk()
        self.root.title(title or f"OctavianOS — {target.stem}")
        self.root.geometry("960x640")
        self.root.configure(bg=THEME["bg"])
        self.root.minsize(640, 420)
        self._build()
        self.root.after(80, self._drain)
        self.root.protocol("WM_DELETE_WINDOW", self._close)

    # ------------------------------------------------------------------ ui
    def _build(self) -> None:
        header = tk.Frame(self.root, bg=THEME["panel"], height=54)
        header.pack(fill="x")
        header.pack_propagate(False)
        tk.Label(
            header, text=f"  {self.target.name}", bg=THEME["panel"], fg=THEME["fg"],
            font=("DejaVu Sans", 13, "bold"), anchor="w",
        ).pack(side="left", fill="y")
        tk.Label(
            header, text=str(self.target.parent), bg=THEME["panel"], fg="#7d8aa5",
            font=("DejaVu Sans", 9), anchor="w",
        ).pack(side="left", fill="y", padx=(6, 0))

        form = tk.Frame(self.root, bg=THEME["bg"])
        form.pack(fill="x", padx=12, pady=(10, 4))

        tk.Label(form, text="Arguments", bg=THEME["bg"], fg="#9fb0cc",
                 font=THEME["ui"]).grid(row=0, column=0, sticky="w")
        self.args = tk.Entry(form, bg=THEME["panel"], fg=THEME["fg"],
                             insertbackground=THEME["fg"], relief="flat", font=THEME["mono"])
        self.args.grid(row=1, column=0, sticky="ew", padx=(0, 8), ipady=5)
        form.columnconfigure(0, weight=1)

        self.run_btn = tk.Button(form, text="▶  Run", command=self.run, bg=THEME["accent"],
                                 fg="#04101f", relief="flat", font=("DejaVu Sans", 10, "bold"),
                                 padx=16, cursor="hand2")
        self.run_btn.grid(row=1, column=1, padx=4)
        self.stop_btn = tk.Button(form, text="■  Stop", command=self.stop, bg="#2a3348",
                                  fg=THEME["fg"], relief="flat", font=THEME["ui"],
                                  padx=14, state="disabled", cursor="hand2")
        self.stop_btn.grid(row=1, column=2, padx=4)
        tk.Button(form, text="Clear", command=self.clear, bg="#2a3348", fg=THEME["fg"],
                  relief="flat", font=THEME["ui"], padx=12, cursor="hand2"
                  ).grid(row=1, column=3, padx=4)

        body = tk.Frame(self.root, bg=THEME["bg"])
        body.pack(fill="both", expand=True, padx=12, pady=6)
        self.out = tk.Text(body, bg="#0a0f18", fg=THEME["fg"], insertbackground=THEME["fg"],
                           relief="flat", font=THEME["mono"], wrap="word", padx=10, pady=8)
        sb = tk.Scrollbar(body, command=self.out.yview, relief="flat")
        self.out.configure(yscrollcommand=sb.set)
        self.out.pack(side="left", fill="both", expand=True)
        sb.pack(side="right", fill="y")
        self.out.tag_config("err", foreground=THEME["err"])
        self.out.tag_config("ok", foreground=THEME["ok"])
        self.out.tag_config("dim", foreground="#6b7891")

        self.status = tk.Label(self.root, text="Ready", bg=THEME["panel"], fg="#9fb0cc",
                               anchor="w", font=("DejaVu Sans", 9), padx=12)
        self.status.pack(fill="x", side="bottom", ipady=4)

        self.args.bind("<Return>", lambda _e: self.run())
        self.root.bind("<Control-Return>", lambda _e: self.run())
        self.root.bind("<Control-l>", lambda _e: self.clear())
        self._write(f"OctavianOS app runner\nTarget : {self.target}\nPython : {sys.executable}\n"
                    f"CWD    : {self.cwd}\n\n", "dim")

    # -------------------------------------------------------------- actions
    def _write(self, text: str, tag: str | None = None) -> None:
        self.out.insert("end", text, tag or ())
        self.out.see("end")

    def clear(self) -> None:
        self.out.delete("1.0", "end")

    def run(self) -> None:
        if self.proc and self.proc.poll() is None:
            return
        argv = [sys.executable, "-u", str(self.target)]
        extra = self.args.get().strip()
        if extra:
            argv += shlex.split(extra)
        env = dict(os.environ)
        env.setdefault("PYTHONUNBUFFERED", "1")
        env.setdefault("MPLBACKEND", "Agg")
        self._write(f"\n$ {' '.join(shlex.quote(a) for a in argv)}\n", "dim")
        self.started = time.time()
        self.status.configure(text="Running…", fg=THEME["accent"])
        self.run_btn.configure(state="disabled")
        self.stop_btn.configure(state="normal")
        try:
            self.proc = subprocess.Popen(
                argv, cwd=str(self.cwd), stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT, text=True, bufsize=1, env=env,
                start_new_session=True,
            )
        except OSError as exc:
            self._write(f"failed to start: {exc}\n", "err")
            self._finish(-1)
            return
        threading.Thread(target=self._pump, args=(self.proc,), daemon=True).start()

    def _pump(self, proc: subprocess.Popen) -> None:
        assert proc.stdout is not None
        for line in proc.stdout:
            self.q.put(line)
        proc.wait()
        self.q.put(f"\x00EXIT:{proc.returncode}")

    def _drain(self) -> None:
        try:
            while True:
                item = self.q.get_nowait()
                if item.startswith("\x00EXIT:"):
                    self._finish(int(item.split(":", 1)[1]))
                else:
                    self._write(item)
        except queue.Empty:
            pass
        self.root.after(80, self._drain)

    def _finish(self, code: int) -> None:
        elapsed = time.time() - self.started if self.started else 0
        tag = "ok" if code == 0 else "err"
        self._write(f"\n[exit {code} · {elapsed:.1f}s]\n", tag)
        self.status.configure(text=f"Finished — exit {code} in {elapsed:.1f}s",
                              fg=THEME["ok"] if code == 0 else THEME["err"])
        self.run_btn.configure(state="normal")
        self.stop_btn.configure(state="disabled")

    def stop(self) -> None:
        if self.proc and self.proc.poll() is None:
            try:
                os.killpg(os.getpgid(self.proc.pid), signal.SIGTERM)
            except OSError:
                self.proc.terminate()
            self._write("\n[termination requested]\n", "err")

    def _close(self) -> None:
        self.stop()
        self.root.destroy()

    def mainloop(self) -> None:
        self.root.mainloop()


def headless(target: Path, argv: list[str]) -> int:
    """No display available: behave like the original CLI."""
    return subprocess.call([sys.executable, str(target), *argv])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="OctavianOS universal GUI app runner")
    ap.add_argument("--target", required=True, help="Python script to run")
    ap.add_argument("--title", default=None)
    ap.add_argument("--cwd", default=None)
    ap.add_argument("--headless", action="store_true")
    ap.add_argument("rest", nargs=argparse.REMAINDER)
    args = ap.parse_args(argv)

    target = Path(args.target).expanduser().resolve()
    if not target.is_file():
        print(f"error: target not found: {target}", file=sys.stderr)
        return 2

    if args.headless or tk is None or not os.environ.get("DISPLAY"):
        return headless(target, [a for a in args.rest if a != "--"])

    AppRunner(target, args.title, Path(args.cwd) if args.cwd else None).mainloop()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
