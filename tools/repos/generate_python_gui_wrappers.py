#!/usr/bin/env python3
"""Generate GUI launchers for every CLI-only Python app in the repo catalog.

For each Python CLI entry point that looks like a real application (not a
test, lint script, or packaging stub) this emits:

  * ``apps/repo-gui/generated/<slug>.py``  — a thin GUI launcher that opens
    the universal OctavianOS app runner on the original script.
  * ``apps/repo-gui/generated/<slug>.desktop`` — a freedesktop entry so the
    app appears in desktop menus.
  * ``desktop/repo_gui_launchers.json`` — index consumed by the staging step
    and the Application Center.

Usage:
    generate_python_gui_wrappers.py --catalog desktop/repo_app_catalog.json \
        --repos /workspace/repos --out apps/repo-gui/generated
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

EXCLUDE_PARTS = {
    "tests", "test", "testing", "__pycache__", "docs", "examples",
    "scripts", "tools", "migrations", "node_modules", ".git",
}
EXCLUDE_NAMES = {
    "setup.py", "conftest.py", "__init__.py", "noxfile.py", "manage.py",
    "conf.py", "version.py",
}
EXCLUDE_PREFIXES = ("check_", "test_", "lint_", "verify_", "audit_", "smoke_")


def is_real_app(rel: str) -> bool:
    p = Path(rel)
    if p.name in EXCLUDE_NAMES:
        return False
    if p.name.startswith(EXCLUDE_PREFIXES):
        return False
    parts = set(p.parts[:-1])
    if parts & EXCLUDE_PARTS:
        return False
    return True


def slugify(rel: str) -> str:
    s = rel.replace("/", "-")
    s = re.sub(r"\.py$", "", s)
    s = re.sub(r"[^A-Za-z0-9._-]+", "-", s).strip("-").lower()
    return s[:90]


def humanize(rel: str) -> str:
    stem = Path(rel).stem.replace("_", " ").replace("-", " ").strip()
    return stem.title() or "App"


LAUNCHER_TEMPLATE = '''#!/usr/bin/env python3
"""Auto-generated OctavianOS GUI launcher for {rel}.

Generated by tools/repos/generate_python_gui_wrappers.py — do not edit.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
RUNNER = HERE.parents[1] / "octavian_app_runner.py"
TARGET = Path({target!r})

if not TARGET.is_file():
    TARGET = Path("/opt/octavianos/repos/{rel}")

sys.path.insert(0, str(RUNNER.parent))
import octavian_app_runner as runner  # noqa: E402

if __name__ == "__main__":
    raise SystemExit(runner.main(["--target", str(TARGET), "--title", {title!r}]))
'''

DESKTOP_TEMPLATE = """[Desktop Entry]
Type=Application
Version=1.0
Name={title}
Comment=OctavianOS repo app ({repo}) — GUI launcher for {rel}
Exec=/opt/octavianos/apps/repo-gui/generated/{slug}.py
Icon=utilities-terminal
Terminal=false
Categories=Development;Utility;
X-OctavianOS-Repo={repo}
X-OctavianOS-Source={rel}
X-OctavianOS-GuiWrapper=true
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--catalog", default="desktop/repo_app_catalog.json")
    ap.add_argument("--repos", default="/workspace/repos")
    ap.add_argument("--out", default="apps/repo-gui/generated")
    ap.add_argument("--index", default="desktop/repo_gui_launchers.json")
    args = ap.parse_args()

    catalog = json.loads(Path(args.catalog).read_text())
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    repos_root = Path(args.repos).resolve()

    launchers = []
    for repo in catalog["repos"]:
        for app in repo["apps"]:
            if app["kind"] != "python-cli":
                continue
            rel = app["rel"]
            if not is_real_app(rel):
                continue
            slug = slugify(rel)
            title = humanize(rel)
            target = str(repos_root / rel)

            py = out / f"{slug}.py"
            py.write_text(LAUNCHER_TEMPLATE.format(rel=rel, target=target, title=title))
            py.chmod(0o755)

            (out / f"{slug}.desktop").write_text(DESKTOP_TEMPLATE.format(
                title=title, repo=repo["name"], rel=rel, slug=slug))

            launchers.append({
                "slug": slug, "title": title, "repo": repo["name"],
                "source": rel, "launcher": str(py), "desktop": str(out / f"{slug}.desktop"),
                "kind": "python-gui-wrapper",
            })

    Path(args.index).write_text(json.dumps({
        "schema": "octavianos.repo-gui-launchers/1",
        "count": len(launchers),
        "launchers": launchers,
    }, indent=2) + "\n")

    print(f"generated {len(launchers)} GUI launchers -> {out}")
    print(f"index -> {args.index}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
